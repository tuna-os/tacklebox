func TestParseBLSEntry(t *testing.T) {
	cases := []struct {
		name       string
		body       string
		wantLinux  string
		wantInitrd string
	}{
		{
			name:       "well-formed entry",
			body:       "title bazzite\nlinux /EFI/bazzite/vmlinuz\ninitrd /EFI/bazzite/initrd.img\noptions root=LABEL=TBOX_STORE\n",
			wantLinux:  "/EFI/bazzite/vmlinuz",
			wantInitrd: "/EFI/bazzite/initrd.img",
		},
		{
			name:       "extra whitespace + tabs",
			body:       "title  Bazzite Live\nlinux\t/images/pxeboot/bazzite/vmlinuz\ninitrd  /images/pxeboot/bazzite/initrd.img\n",
			wantLinux:  "/images/pxeboot/bazzite/vmlinuz",
			wantInitrd: "/images/pxeboot/bazzite/initrd.img",
		},
		{
			name:       "missing linux line",
			body:       "title x\ninitrd /a\n",
			wantLinux:  "",
			wantInitrd: "/a",
		},
		{
			name:       "blank lines and comments are tolerated",
			body:       "\n# generated by tacklebox\n\nlinux /vmlinuz\ninitrd /initrd.img\n\n",
			wantLinux:  "/vmlinuz",
			wantInitrd: "/initrd.img",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := ParseBLSEntry(tc.body)
			if got.Linux != tc.wantLinux {
				t.Errorf("linux = %q, want %q", got.Linux, tc.wantLinux)
			}
			if got.Initrd != tc.wantInitrd {
				t.Errorf("initrd = %q, want %q", got.Initrd, tc.wantInitrd)
			}
		})
	}
}

func TestCheckBLSResolves(t *testing.T) {
	files := map[string]bool{
		"EFI/bazzite/vmlinuz":    true,
		"EFI/bazzite/initrd.img": true,
		"loader/loader.conf":     true,
	}
	cases := []struct {
		name    string
		entry   BLSEntry
		wantErr bool
	}{
		{
			name:    "both resolve",
			entry:   BLSEntry{Name: "ok.conf", Linux: "/EFI/bazzite/vmlinuz", Initrd: "/EFI/bazzite/initrd.img"},
			wantErr: false,
		},
		{
			name:    "linux missing",
			entry:   BLSEntry{Name: "bad.conf", Linux: "/EFI/aurora/vmlinuz", Initrd: "/EFI/bazzite/initrd.img"},
			wantErr: true,
		},
		{
			name:    "initrd missing",
			entry:   BLSEntry{Name: "bad.conf", Linux: "/EFI/bazzite/vmlinuz", Initrd: "/EFI/aurora/initrd.img"},
			wantErr: true,
		},
		{
			name:    "both empty",
			entry:   BLSEntry{Name: "empty.conf"},
			wantErr: true,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			r := CheckBLSResolves(tc.entry, files, "ESP")
			if (r.Err != nil) != tc.wantErr {
				t.Errorf("got err=%v, wantErr=%v", r.Err, tc.wantErr)
			}
		})
	}
}

func TestBLSOption(t *testing.T) {
	opts := "root=live:CDLABEL=X rd.live.squashimg=combined.rootfs.sfs tacklebox.root=bluefin"
	if got := BLSOption(opts, "rd.live.squashimg"); got != "combined.rootfs.sfs" {
		t.Errorf("squashimg = %q", got)
	}
	if got := BLSOption(opts, "tacklebox.root"); got != "bluefin" {
		t.Errorf("tacklebox.root = %q", got)
	}
	// Prefix must not match a longer key (tacklebox.root vs tacklebox.rootflags).
	if got := BLSOption("tacklebox.rootflags=x", "tacklebox.root"); got != "" {
		t.Errorf("prefix collision: got %q, want empty", got)
	}
}

func TestBLSSquashimg(t *testing.T) {
	// Current spelling (tbox-live module).
	if got := BLSSquashimg("root=tbox:CDLABEL=X tacklebox.live.squashimg=alpha.rootfs.sfs"); got != "alpha.rootfs.sfs" {
		t.Errorf("tbox-live spelling = %q", got)
	}
	// Legacy dmsquash-live spelling: ISOs built before the tbox-live
	// switch must stay verifiable.
	if got := BLSSquashimg("root=live:CDLABEL=X rd.live.squashimg=beta.rootfs.sfs"); got != "beta.rootfs.sfs" {
		t.Errorf("legacy spelling = %q", got)
	}
	if got := BLSSquashimg("root=LABEL=TBOX_STORE rw"); got != "" {
		t.Errorf("non-live entry = %q, want empty", got)
	}
}
